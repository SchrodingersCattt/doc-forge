def test_fixtures_are_portable() -> None:
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        if path.suffix.casefold() == ".docx":
            with zipfile.ZipFile(path) as package:
                payload = b"\n".join(package.read(name) for name in package.namelist() if name.endswith(".xml"))
            text = payload.decode("utf-8", errors="replace")
        elif path.suffix.casefold() == ".png":
            continue
        else:
            text = path.read_text(encoding="utf-8")
        assert "SchrodingersCattt" not in text
        assert not _ABS_PATH.search(text)


