@pytest.mark.parametrize(
    ("source_name", "output_name", "expected"),
    [
        ("missing.md", "out.docx", {"resource.missing"}),
        ("missing.md", "out.tex", {"resource.missing"}),
        ("loss.tex", "out.md", {"latex.unsupported_command", "latex.unsupported_environment"}),
        ("loss.tex", "out.docx", {"latex.unsupported_command", "latex.unsupported_environment"}),
        ("native.docx", "out.md", {"docx.textboxes"}),
        ("native.docx", "out.tex", {"docx.textboxes"}),
    ],
)
def test_strict_conversion_publishes_nothing(tmp_path: Path, source_name: str, output_name: str, expected: set[str]) -> None:
    source = ROOT / source_name
    before = source.read_bytes()
    kept = tmp_path / output_name
    kept.write_bytes(b"SENTINEL")
    with pytest.raises(ConversionError) as caught:
        convert(source, kept, loss_policy="error", force=True)
    assert caught.value.code == "LOSS_POLICY"
    assert expected <= _codes(caught.value.diagnostics)
    assert kept.read_bytes() == b"SENTINEL"
    assert source.read_bytes() == before

    fresh = tmp_path / "fresh" / output_name
    assert cli_main(["convert", str(source), str(fresh), "--loss-policy", "error", "--force"]) == 2
    assert not fresh.exists()
    assert source.read_bytes() == before


