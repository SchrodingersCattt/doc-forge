def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _pandoc_version() -> str | None:
    if shutil.which("pandoc") is None:
        return None
    completed = subprocess.run(
        ["pandoc", "--version"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    first = completed.stdout.splitlines()[0] if completed.stdout else ""
    match = re.match(r"pandoc\s+(\S+)", first.strip())
    return match.group(1) if match else ""


def _require_pandoc() -> str:
    version = _pandoc_version()
    if not version:
        pytest.skip("Pandoc is required for this golden. The skip is not a pass.")
    return version


def _inline(node) -> dict:
    return {
        "kind": node.kind,
        "text": node.text,
        "attrs": {key: value for key, value in node.attrs},
        "children": [_inline(child) for child in node.children],
    }


def supported_view(document: SemanticDocument) -> dict:
    """Projection of the declared intersection. Resource ids and package paths are omitted."""

    def block(node) -> dict:
        attrs = {key: value for key, value in node.attrs if key != "resource"}
        if "path" in attrs and attrs["path"]:
            attrs["path"] = PurePosixPath(attrs["path"]).name
        return {
            "kind": node.kind,
            "attrs": attrs,
            "inlines": [_inline(item) for item in node.inlines],
            "children": [block(child) for child in node.children],
        }

    return {
        "title": document.metadata.title,
        "blocks": [block(item) for item in document.blocks],
        "references": [item.project() for item in document.references],
    }


def _kinds(block) -> list[str]:
    return [node.kind for node in block.inlines]


def _grid(block) -> list[list[str]]:
    return [[cell.plain() for cell in row.children] for row in block.children]


def _figure_sha(document: SemanticDocument) -> str:
    figure = next(block for block in document.blocks if block.kind == "figure")
    resource = document.resource(figure.attr("resource"))
    assert resource is not None and resource.sha256
    return resource.sha256


def normalize_gfm(text: str) -> str:
    """Stable Pandoc GFM: basename media paths and canonical table separators."""

    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines: list[str] = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if _is_separator(line):
            cells = [part.strip() for part in line.strip().strip("|").split("|")]
            line = "| " + " | ".join("---" for _ in cells) + " |"
        line = re.sub(
            r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+[^)]*)?\)",
            lambda match: f"![{match.group(1)}]({PurePosixPath(match.group(2)).name})",
            line,
        )
        lines.append(line)
    collapsed = re.sub(r"\n{3,}", "\n\n", "\n".join(lines).strip())
    return collapsed + "\n"


def _is_separator(line: str) -> bool:
    stripped = line.strip()
    if not (stripped.startswith("|") and stripped.endswith("|")):
        return False
    cells = [part.strip() for part in stripped.strip("|").split("|")]
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells)


def normalize_pandoc_tex(text: str) -> str:
    """Drop the export timestamp and rewrite graphics paths to file names."""

    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"^% Auto-generated by docforge docx2tex.*\n", "", text)
    text = re.sub(r"\\hypertarget\{[^}]+\}\{%", "", text)
    text = re.sub(r"\\label\{[^}]+\}", "", text)
    text = re.sub(
        r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}",
        lambda match: "\\includegraphics{" + PurePosixPath(match.group(1)).name + "}",
        text,
    )
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def _codes(diagnostics) -> set[str]:
    return {item.code for item in diagnostics}


def test_semantic_sources_share_the_supported_view() -> None:
    markdown = read(ROOT / "semantic.md")
    latex = read(ROOT / "semantic.tex")
    assert supported_view(markdown.document) == supported_view(latex.document)
    assert markdown.document.projection()["references"] == [
        {"kind": "citation", "key": "ada2024", "target": ""},
    ]
    math = [block.attr("tex") for block in markdown.document.blocks if block.kind == "math"]
    assert math == ["E = mc^2", "\\begin{align}\na &= b \\\\\nc &= d\n\\end{align}"]
    assert _figure_sha(markdown.document) == _digest(MARK)
    for document in (markdown.document, latex.document):
        for block in document.walk():
            path = block.attr("path")
            assert not path.startswith("/")
            assert ".." not in PurePosixPath(path).parts
            assert not _ABS_PATH.search(path)


def test_markdown_latex_round_trip_api_and_cli(tmp_path: Path) -> None:
    source = ROOT / "semantic.md"
    before = source.read_bytes()
    tex = tmp_path / "semantic.tex"
    back = tmp_path / "back.md"
    first = convert(source, tex, force=True)
    second = convert(tex, back, force=True)
    assert first.execution_mode == second.execution_mode == "REBUILD"
    assert tex.read_text(encoding="utf-8") == (ROOT / "semantic.tex").read_text(encoding="utf-8")
    assert read(back).document.projection() == read(source).document.projection()
    assert (tmp_path / "media" / "mark.png").read_bytes() == MARK.read_bytes()
    assert source.read_bytes() == before

    cli_tex = tmp_path / "cli.tex"
    cli_back = tmp_path / "cli.md"
    assert cli_main(["convert", str(source), str(cli_tex), "--force"]) == 0
    assert cli_main(["convert", str(cli_tex), str(cli_back), "--force"]) == 0
    assert read(cli_back).document.projection() == read(source).document.projection()

    origin = ROOT / "semantic.tex"
    origin_before = origin.read_bytes()
    markdown = tmp_path / "from-tex.md"
    restored = tmp_path / "restored.tex"
    convert(origin, markdown, force=True)
    convert(markdown, restored, force=True)
    assert read(restored).document.projection() == read(origin).document.projection()
    assert supported_view(read(markdown).document) == supported_view(read(origin).document)
    assert origin.read_bytes() == origin_before
    assert cli_main(["convert", str(origin), str(tmp_path / "cli-from-tex.md"), "--force"]) == 0


